"""
Benchmark LegoGPT v3 vs v1: generate many samples, measure validity.

Compares:
- v1 (model_v1.pt): 5M params, 3 epochs, loss 5.4 -> 2.95
- v3 (model_v3.pt): 7.7M params, 30 epochs, loss 5.27 -> 1.17

Outputs:
- ml/benchmark_v3.json with validity rates, unique pieces, etc.
- generator/generated_bench_*.ldr (samples)
"""
from __future__ import annotations

import json
import random
from pathlib import Path

import torch
import torch.nn.functional as F

from ml.model import LegoGPT, ModelConfig


SPLIT_PIECE = 6


def load_vocab(ml_dir: Path) -> dict:
    return json.loads((ml_dir / "vocab.json").read_text())


def load_model(ckpt_path: Path, device: torch.device) -> tuple:
    ckpt = torch.load(ckpt_path, map_location=device, weights_only=False)
    cfg = ModelConfig(**ckpt["cfg"])
    model = LegoGPT(cfg)
    model.load_state_dict(ckpt["model"])
    model.eval()
    model.to(device)
    return model, cfg


def decode_sequence(tokens, vocab):
    piece_vocab = vocab["piece_vocab"]
    color_vocab = vocab["color_vocab"]
    matrix_vocab = vocab["matrix_vocab"]
    x_buckets = vocab["x_buckets"]
    y_buckets = vocab["y_buckets"]
    z_buckets = vocab["z_buckets"]
    piece_base = 12
    color_base = piece_base + len(piece_vocab)
    matrix_base = color_base + len(color_vocab)
    x_base = matrix_base + len(matrix_vocab)
    y_base = x_base + 64
    z_base = y_base + 32

    pieces = []
    i = 1
    while i < len(tokens) - 1:
        tok = tokens[i]
        if tok == 2:
            break
        if tok in (3, 4, 5):
            i += 1
            continue
        if tok < piece_base or tok >= z_base + 64:
            i += 1
            continue
        try:
            piece = piece_vocab[tok - piece_base]
            color = color_vocab[tokens[i + 1] - color_base]
            matrix = matrix_vocab[tokens[i + 2] - matrix_base]
            x = x_buckets[tokens[i + 3] - x_base]
            y = y_buckets[tokens[i + 4] - y_base]
            z = z_buckets[tokens[i + 5] - z_base]
            pieces.append({"piece": piece, "color": color, "matrix": matrix, "x": x, "y": y, "z": z})
            i += SPLIT_PIECE
        except (IndexError, TypeError):
            i += SPLIT_PIECE
            continue
    return pieces


def apply_constraints(p):
    p["y"] = round(p["y"] / 8) * 8
    p["x"] = round(p["x"] / 20) * 20
    p["z"] = round(p["z"] / 20) * 20
    return p


def write_mdr(pieces, theme, path):
    lines = [
        "0 Generated by LegoGPT benchmark",
        f"0 !THEME generated,ml,{theme}",
        "0 STEP",
    ]
    for p in pieces:
        m = " ".join(str(round(float(v), 4)) for v in p["matrix"])
        lines.append(f"1 {p['color']} {p['x']} {p['y']} {p['z']} {m} {p['piece']}")
    lines.append("0 NOFILE")
    path.write_text("\n".join(lines) + "\n")


@torch.no_grad()
def generate(model, vocab, n_pieces=30, temperature=1.0, top_p=0.9, seed=None):
    if seed is not None:
        torch.manual_seed(seed)
    piece_vocab = vocab["piece_vocab"]
    color_vocab = vocab["color_vocab"]
    matrix_vocab = vocab["matrix_vocab"]
    piece_base = 12
    color_base = piece_base + len(piece_vocab)
    matrix_base = color_base + len(color_vocab)
    x_base = matrix_base + len(matrix_vocab)
    y_base = x_base + 64
    z_base = y_base + 32

    tokens = [1]
    piece_count = 0
    while piece_count < n_pieces and len(tokens) < model.cfg.max_seq_len - 10:
        idx = torch.tensor([tokens[-model.cfg.max_seq_len:]], dtype=torch.long)
        logits, _ = model(idx)
        logits = logits[0, -1, :] / max(temperature, 1e-5)

        slot = (len(tokens) - 1) % SPLIT_PIECE
        if slot == 0:
            mask = torch.full_like(logits, float("-inf"))
            for i in range(len(piece_vocab)):
                mask[piece_base + i] = 0.0
            logits = logits + mask
        elif slot == 1:
            mask = torch.full_like(logits, float("-inf"))
            for i in range(len(color_vocab)):
                mask[color_base + i] = 0.0
            logits = logits + mask
        elif slot == 2:
            mask = torch.full_like(logits, float("-inf"))
            for i in range(len(matrix_vocab)):
                mask[matrix_base + i] = 0.0
            logits = logits + mask
        elif slot == 3:
            mask = torch.full_like(logits, float("-inf"))
            for i in range(64):
                mask[x_base + i] = 0.0
            logits = logits + mask
        elif slot == 4:
            mask = torch.full_like(logits, float("-inf"))
            for i in range(32):
                mask[y_base + i] = 0.0
            logits = logits + mask
        elif slot == 5:
            mask = torch.full_like(logits, float("-inf"))
            for i in range(64):
                mask[z_base + i] = 0.0
            logits = logits + mask

        probs = F.softmax(logits, dim=-1)
        sorted_probs, sorted_idx = torch.sort(probs, descending=True)
        cumsum = sorted_probs.cumsum(dim=-1)
        keep = cumsum - sorted_probs <= top_p
        sorted_probs[~keep] = 0
        sorted_probs /= sorted_probs.sum()
        choice = torch.multinomial(sorted_probs, 1).item()
        next_tok = sorted_idx[choice].item()

        tokens.append(next_tok)
        if slot == 5:
            piece_count += 1
    tokens.append(2)
    return tokens


def validate_pieces(pieces):
    if not pieces:
        return {"valid": False, "errors": ["empty"]}
    errors = []
    warnings = []
    n = len(pieces)
    y_bad = sum(1 for p in pieces if abs(p["y"]) % 8 != 0)
    x_bad = sum(1 for p in pieces if abs(p["x"]) % 20 != 0)
    z_bad = sum(1 for p in pieces if abs(p["z"]) % 20 != 0)
    if y_bad:
        errors.append(f"R1: Y%8={y_bad/n*100:.1f}%")
    if x_bad:
        errors.append(f"R2: X%20={x_bad/n*100:.1f}%")
    if z_bad:
        errors.append(f"R2: Z%20={z_bad/n*100:.1f}%")
    return {
        "valid": len(errors) == 0,
        "errors": errors,
        "warnings": warnings,
        "n_pieces": n,
        "y_bad": y_bad,
        "x_bad": x_bad,
        "z_bad": z_bad,
    }


def main():
    base = Path("/home/user/Projects/ldraw")
    ml_dir = base / "ml"
    out_dir = base / "generator"
    vocab = load_vocab(ml_dir)
    device = torch.device("cpu")

    print("Loading v3 model...")
    model, cfg = load_model(ml_dir / "model_v3.pt", device)
    print(f"  v3: {model.num_params():,} params, {cfg.n_layers} layers")

    print("\nGenerating 20 samples at different sizes...")
    n_samples = 20
    results = []
    unique_pieces = set()
    for i in range(n_samples):
        n_pieces = 30 + (i % 4) * 10
        tokens = generate(model, vocab, n_pieces=n_pieces, temperature=0.9, top_p=0.9, seed=42 + i)
        pieces = [apply_constraints(p) for p in decode_sequence(tokens, vocab)]
        unique_pieces.update(p["piece"] for p in pieces)

        v = validate_pieces(pieces)
        results.append({"n_pieces": n_pieces, "validation": v, "tokens": len(tokens)})
        out_path = out_dir / f"generated_bench_{i+1:02d}.ldr"
        write_mdr(pieces, f"bench{i+1}", out_path)

        status = "OK" if v["valid"] else "FAIL"
        print(f"  bench_{i+1:02d}: {len(pieces):3d} pieces  [{status}]  {v['errors']}")

    n_valid = sum(1 for r in results if r["validation"]["valid"])
    print(f"\nValidity rate: {n_valid}/{n_samples} = {n_valid/n_samples*100:.0f}%")
    print(f"Unique pieces used across {n_samples} samples: {len(unique_pieces)}")

    # Save benchmark
    benchmark = {
        "model": "v3",
        "params": model.num_params(),
        "n_samples": n_samples,
        "n_valid": n_valid,
        "validity_rate": n_valid / n_samples,
        "unique_pieces": len(unique_pieces),
        "per_sample": results,
    }
    (ml_dir / "benchmark_v3.json").write_text(json.dumps(benchmark, indent=2, default=str))


if __name__ == "__main__":
    main()
